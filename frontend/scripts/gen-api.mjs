// Generates src/api/schema.d.ts from the rswag-built OpenAPI document.
//
// OpenAPI 3.0 has no tuple type, so the backend describes `[date, value]`
// pairs as fixed-length arrays of `string | number`. Left alone those
// generate as `(string | number)[]`; the transform below turns exactly those
// schemas (matched on their fixed length and description) back into the
// tuples the API actually sends. Everything else is openapi-typescript's
// default output.
import { writeFileSync } from "node:fs";
import openapiTS, { astToString } from "openapi-typescript";
import ts from "typescript";

const SOURCE = new URL("../../swagger/v1/swagger.yaml", import.meta.url);
const OUTPUT = new URL("../src/api/schema.d.ts", import.meta.url);

const STRING = ts.factory.createKeywordTypeNode(ts.SyntaxKind.StringKeyword);
const NUMBER = ts.factory.createKeywordTypeNode(ts.SyntaxKind.NumberKeyword);
const NULL = ts.factory.createLiteralTypeNode(ts.factory.createNull());
const tuple = (...members) => ts.factory.createTupleTypeNode(members);

/** description prefix + fixed length → the tuple it stands for */
const TUPLES = [
  // DateValuePair: [ISO date, value]
  { description: "[ISO date, value]", length: 2, type: () => tuple(STRING, NUMBER) },
  // Security price_chart rows: [ISO date, close, volume | null]
  { description: "[ISO date, close, volume]", length: 3, type: () => tuple(STRING, NUMBER, ts.factory.createUnionTypeNode([NUMBER, NULL])) },
];

const ast = await openapiTS(SOURCE, {
  transform(schema) {
    if (schema.type !== "array" || schema.minItems == null || schema.minItems !== schema.maxItems) return undefined;
    const match = TUPLES.find(
      (t) => t.length === schema.minItems && typeof schema.description === "string" && schema.description.startsWith(t.description),
    );
    return match?.type();
  },
});

const banner = `/**
 * This file was auto-generated by openapi-typescript from swagger/v1/swagger.yaml.
 * Do not make direct changes to the file — run \`npm run gen:api\` (scripts/gen-api.mjs).
 */

`;
writeFileSync(OUTPUT, banner + astToString(ast));
